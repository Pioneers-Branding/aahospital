                      <h3>Pre-Evaluation and Diagnosis</h3>
                      <p>
                      The first step in pediatric ophthalmology at A.A Hospitals is a comprehensive pre-evaluation to assess your child's vision and eye health. This evaluation includes:

                      </p>
                      <ul>
                        <li>
                          <b>Medical History Review : </b>Understanding the child's medical history, including any previous eye conditions or treatments.


                        </li>
                        <li>
                          <b>Visual Acuity Test:</b> Measuring how well the child can see at various distances using age-appropriate methods.

                        </li>
                        <li>
                          <b>Eye Alignment and Movement Tests</b> Checking for issues with eye alignment and coordination.


                        </li>
                        <li>
                          <b>Refraction Test : </b> Determining if the child needs glasses or contact lenses.

                        </li>
                        <li><b>Imaging Studies:</b> Using advanced imaging techniques like retinal imaging and OCT to obtain detailed images of the eye structures.</li>
                        
                      </ul>
                    </div>
                  </blockquote>

                
                  
                   <blockquote>
                    <div class="col-lg-12">
                      <h2>Common Pediatric Eye Conditions and Treatments</h2>
                    
                      <p>
                      Pediatric ophthalmology covers a wide range of eye conditions, including:

                      </p>
                      <ul>
                        <li>
                          <b>Amblyopia (Lazy Eye):</b>Diagnosis- Detecting reduced vision in one eye due to the brain favoring the other eye.

                          <br>
                          <b>Treatment :</b>Patching the stronger eye, atropine drops, or corrective lenses to improve vision in the weaker eye.

                        </li>
                        <li>
                          <b>Strabismus (Crossed Eyes):</b>Diagnosis: Identifying misalignment of the eyes where they do not look in the same direction simultaneously.<br>
                          <b>Treatment:</b> Glasses, prism lenses, eye muscle exercises, or surgery to correct eye alignment.

                        </li>
                        <li>
                          <b>Refractive Errors (Nearsightedness, Farsightedness, Astigmatism):</b> Diagnosis -   Detecting issues with how light is focused on the retina.

                          <br>
                             <b>Treatment</b> Prescribing glasses or contact lenses to correct vision.


                        </li>
                        <li><b>Congenital Eye Disorders</b>Diagnosis- Identifying eye conditions present at birth, such as congenital cataracts or glaucoma. <br>
                        <b>Treatment: </b> Surgical intervention or specialized medical treatment depending on the condition.</li>

                      </ul>
                    </div>
                  </blockquote>
                  
                  
                  
