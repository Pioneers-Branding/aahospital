                      <h2>The Surgical Process</h2>
                      <p>
                        Cataract surgery at A.A Hospital is typically performed
                        as an outpatient procedure under local anesthesia,
                        ensuring comfort and minimizing recovery time. The
                        entire procedure usually takes about 15-30 minutes per
                        eye and involves the following steps:
                      </p>
                      <ul>
                        <li>
                          <b>Anaesthesia:</b> Local anaesthesia is administered
                          to numb the eye, and a mild sedative may be given to
                          help you relax.
                        </li>
                        <li>
                          <b>Incision:</b>A small incision is made at the edge
                          of the cornea. For those opting for femtosecond
                          laser-assisted cataract surgery, the laser creates
                          precise incisions without the use of blades.
                        </li>
                        <li>
                          <b>Lens Removal:</b>The cloudy lens is emulsified
                          using ultrasonic waves through a process called
                          phacoemulsification. The emulsified lens fragments are
                          then gently suctioned out of the eye.
                        </li>
                        <li>
                          <b>IOL Insertion:</b> 4. A clear artificial
                          intraocular lens (IOL) is inserted into the same
                          location as the natural lens. The type of IOL
                          (monofocal, multifocal, or toric) is chosen based on
                          your visual needs and lifestyle.
                        </li>
                        <li>
                          <b>Incision Closure:</b>The small incision usually
                          heals without the need for stitches, thanks to its
                          self-sealing design.
                        </li>
                      </ul>
                    </div>
                  </blockquote>

