                <h2>Diabetic Retinopathy Overview</h2>
                <h3>What is Diabetic Retinopathy?</h3>
                <p>
                  Diabetic retinopathy is a complication of diabetes that
                  affects the blood vessels of the retina, the light-sensitive
                  tissue at the back of the eye. High blood sugar levels can
                  cause these blood vessels to swell, leak, or grow abnormally,
                  leading to vision problems and potentially severe vision loss.
                  Diabetic retinopathy often has no early symptoms, making
                  regular eye examinations crucial for people with diabetes.
                  Early detection and timely treatment are key to preventing
                  vision loss.
                </p>
