                      <p>
                       Glaucoma management involves a combination of medical, laser, and surgical treatments tailored to the individual needs of each patient. Our comprehensive treatment options include:
                      </p>
                      <ul>
                        <li>
                          <b>Medications:</b>Eye drops to reduce intraocular pressure by decreasing fluid production or improving fluid drainage. <br>
                                            Oral medications for patients who do not respond well to eye drops.
                        </li>
                        <li>
                          <b>Laser procedures :</b>Laser Peripheral Iridotomy (LPI)- Creates a small hole in the iris to improve fluid drainage in angle-closure glaucoma.
                        </li>
                        <li>
                          <b>Surgical Treatments:</b>○Trabeculectomy - Creates a new drainage pathway for fluid to leave the eye, lowering intraocular pressure.
                        </li>
                        <li>
                          <b>IOL Insertion:</b> 4. A clear artificial
                          intraocular lens (IOL) is inserted into the same
                          location as the natural lens. The type of IOL
                          (monofocal, multifocal, or toric) is chosen based on
                          your visual needs and lifestyle.
                        </li>
