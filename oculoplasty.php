                <blockquote>
                  
                    <h2>Types of Oculoplasty Procedures</h2>

                    <p>
                      Oculoplasty encompasses a wide range of surgical
                      procedures, including:
                    </p>
                    <ul>
                      <li>
                        <h4 style="color: #f89f1d">Eyelid Surgery (Blepharoplasty)</h4>
                        <span><h6 class="mt-3">Upper Blepharoplasty: </h6> Removes excess skin and fat from the
                        upper eyelids to correct droopy eyelids and improve
                        vision.</span>
                        <br />
                        <span><h6 class="mt-3">Lower Blepharoplasty: </h6> Removes or repositions
                        fat from the lower eyelids to reduce puffiness and
                        correct under-eye bags.</span>
                      </li>
                      
                      <li class="mt-3">
                        <h4 style="color: #f89f1d">Ptosis Correction</h4>
                        <span>Surgical procedures to lift droopy eyelids and improve vision obstructed by
                        ptosis.</span>
                      </li>
                      
                      <li class="mt-3">
                        <h4 style="color: #f89f1d">Eyelid Malposition Correction</h4>
                        <span><h6 class="mt-3">Entropion Repair: </h6> Corrects inward-turning eyelids to prevent
                        irritation and damage to the cornea.</span>
                        <br />
                        <span><h6 class="mt-3">Ectropion Repair: </h6> Corrects outward-turning
                        eyelids to improve tear drainage and prevent dryness.</span>
                      </li>
                      
                      <li class="mt-3">
                         <h4 style="color: #f89f1d">Tear Duct Surgery (Dacryocystorhinostomy):</h4>
                        <span>Procedures to unblock tear ducts and improve tear drainage.</span>
                      </li>
                      
                      <li class="mt-3">
                        <h4 style="color: #f89f1d">Orbital Surgery:</h4>
                        <span>Treats orbital fractures, tumors, and other conditions affecting the eye socket.</span>
                      </li>
                      
                    </ul>
                  
                </blockquote>

